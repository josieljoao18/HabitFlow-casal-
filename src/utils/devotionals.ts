export function getDailyVerse(): DevotionalVerse {
  const dayOfYear = Math.floor((new Date().getTime() - new Date(new Date().getFullYear(), 0, 1).getTime()) / 86400000);
  const index = Math.max(0, dayOfYear % DEVOTIONAL_VERSES.length);
  return DEVOTIONAL_VERSES[index];
}

export function getDailyChallenge(): CoupleChallenge {
  const dayOfYear = Math.floor((new Date().getTime() - new Date(new Date().getFullYear(), 0, 1).getTime()) / 86400000);
  const index = Math.max(0, dayOfYear % DAILY_CHALLENGES.length);
  return DAILY_CHALLENGES[index];
}
